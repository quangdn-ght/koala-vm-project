#!/usr/bin/env python3
"""Generate Prometheus file_sd + blackbox DNS modules from websites/sites.json."""
from __future__ import annotations

import json
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "websites" / "sites.json"
OUT = ROOT / "prometheus" / "targets"
BLACKBOX = ROOT / "blackbox" / "blackbox.yml"
BEGIN = "  # BEGIN GENERATED website-dns\n"
END = "  # END GENERATED website-dns\n"

TLS_MODULE = {
    "public": "http_website",
    "origin": "http_website_origin",
    "plain": "http_website_plain",
}

KIND_API_MODULE = {
    "public": "http_website_api",
    "origin": "http_website_origin",
    "plain": "http_website_plain",
}


def _labels(d: dict[str, str]) -> str:
    inner = ", ".join(f"{k}: {json.dumps(v)}" for k, v in d.items())
    return "{" + inner + "}"


def _block(target: str, labels: dict[str, str]) -> str:
    return f'- targets: ["{target}"]\n  labels: {_labels(labels)}\n'


def _dns_module_name(name: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_")
    return f"dns_website_{slug}"


def _hostname(url: str) -> str:
    host = urlparse(url).hostname
    if not host:
        raise ValueError(f"no hostname in {url}")
    return host


def _kind(site: dict) -> str:
    kind = site.get("kind", "web")
    if kind not in ("web", "api"):
        raise ValueError(f"unknown kind={kind} for {site.get('name')}")
    return kind


def _http_module(site: dict) -> str:
    tls = site.get("tls") or (
        "origin"
        if site.get("origin_expected") and site["url"].startswith("https://")
        else "public"
        if site["url"].startswith("https://")
        else "plain"
    )
    table = KIND_API_MODULE if _kind(site) == "api" else TLS_MODULE
    if tls not in table:
        raise ValueError(f"unknown tls={tls} for {site.get('name')}")
    return table[tls]


def _dns_module_yaml(name: str, query_name: str, origin_ip: str) -> str:
    mod = _dns_module_name(name)
    ip_re = re.escape(origin_ip)
    return (
        f"  {mod}:\n"
        f"    prober: dns\n"
        f"    timeout: 5s\n"
        f"    dns:\n"
        f"      query_name: {json.dumps(query_name)}\n"
        f"      query_type: A\n"
        f"      query_class: IN\n"
        f"      recursion_desired: true\n"
        f"      transport_protocol: udp\n"
        f"      preferred_ip_protocol: ip4\n"
        f"      ip_protocol_fallback: false\n"
        f"      valid_rcodes: [NOERROR]\n"
        f"      validate_answer_rrs:\n"
        f"        fail_if_none_matches_regexp:\n"
        f"          - {json.dumps(ip_re)}\n"
    )


def _replace_generated(text: str, body: str) -> str:
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(
            f"{BLACKBOX} missing markers {BEGIN.strip()} / {END.strip()}"
        )
    return text[: start + len(BEGIN)] + body + text[end:]


def main() -> None:
    inv = json.loads(INVENTORY.read_text())
    interval = inv.get("scrape_interval", "1m")
    origin_ip = inv["origin_ip"]
    dns_server = inv.get("dns_server", "1.1.1.1")
    sites = inv["sites"]
    enabled = [s for s in sites if s.get("enabled", True)]

    http_sd: list[str] = []
    dns_sd: list[str] = []
    dns_mods: list[str] = []
    for site in enabled:
        name = site["name"]
        url = site["url"]
        host_name = _hostname(url)
        origin_expected = "true" if site.get("origin_expected") else "false"
        kind = _kind(site)
        labels = {
            "host": name,
            "app": name,
            "group": site["group"],
            "role": "website",
            "kind": kind,
            "origin_expected": origin_expected,
            "__param_module": _http_module(site),
        }
        http_sd.append(_block(url, labels))
        dns_labels = {
            "host": name,
            "app": name,
            "group": site["group"],
            "role": "website",
            "origin_expected": origin_expected,
            "query_name": host_name,
            "__param_module": _dns_module_name(name),
        }
        dns_sd.append(_block(dns_server, dns_labels))
        dns_mods.append(_dns_module_yaml(name, host_name, origin_ip))

    header = (
        f"# Generated from {INVENTORY.relative_to(ROOT)} — do not edit.\n"
        f"# scrape_interval hint: {interval} (jobs blackbox-http-website / blackbox-dns-website).\n"
        f"# Regenerated by: python3 scripts/gen-website-targets.py\n"
    )
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "websites.yml").write_text(header + "\n" + "".join(http_sd))
    (OUT / "websites-dns.yml").write_text(header + "\n" + "".join(dns_sd))

    bb = BLACKBOX.read_text()
    body = "".join(dns_mods) if dns_mods else "  # (no enabled sites)\n"
    BLACKBOX.write_text(_replace_generated(bb, body))
    print(
        f"wrote {len(enabled)} website HTTP+DNS targets "
        f"(enabled={len(enabled)}/{len(sites)}, origin_ip={origin_ip})"
    )


if __name__ == "__main__":
    main()
